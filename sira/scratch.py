"""One-button model from scratch.

  1. corpus     your text folder (cfg.scratch_corpus_dir) or random Wikipedia articles in cfg.scratch_language
  2. tokenizer  byte-level BPE trained on that corpus
  3. pretrain   random-initialised Llama-style model learns LANGUAGE ONLY (next-token prediction)
  4. curriculum a first supervised lesson generated by the Evaluation Core's verified solvers (train namespace only,
                never the hidden eval problems): answer format + the basic skills of every domain
  5. then the normal self-improvement loop takes over (full-weight rejection-sampling fine-tuning).
Every stage is resumable (its output folder is the marker)."""
from __future__ import annotations

import json
import os
import shutil
import threading
import time
import urllib.parse
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from . import intake
from .evalcore import oracle_response
from .trainer import TrainingError

SIZE_PLAN = {  # vocab, seq_len, batch, lr
    "tiny": (4096, 256, 16, 3e-3), "small": (16000, 512, 16, 1e-3), "base": (32000, 1024, 8, 6e-4)}


def parse_wiki_random(raw: bytes):
    d = json.loads(raw.decode("utf-8", "replace"))
    for page in (d.get("query", {}).get("pages") or {}).values():
        text = (page.get("extract") or "").strip()
        if len(text) > 800:
            return page.get("title", ""), text
    return None


class ScratchBuilder:
    def __init__(self, tm):
        self.tm, self.ctx = tm, tm.ctx
        self.cfg, self.bus, self.control = tm.cfg, tm.bus, tm.control
        self.dir = Path(self.ctx.run_dir) / "scratch"
        self.dir.mkdir(exist_ok=True)

    def say(self, msg, level="info"):
        self.bus.emit("scratch", "scratch_builder", msg, level=level)
        self.bus.status("scratch_builder", msg[:80], role="scratch_builder", parent="training_maestro")

    def pick_size(self, hw) -> str:
        if self.cfg.scratch_size != "auto":
            return self.cfg.scratch_size
        if hw.get("cuda") and hw["gpus"]:
            v = hw["gpus"][0]["vram_gb"]
            return "base" if v >= 40 else "small" if v >= 12 else "tiny"
        return "tiny"

    def arch_params(self, size: str) -> tuple[int, int]:
        """(kv_heads, cla_factor) for the chosen architecture preset. kv_heads 0 = size default (GQA)."""
        heads = {"tiny": 4, "small": 6, "base": 12}[size]
        a = self.cfg.scratch_arch
        return {"llama": (0, 1), "gqa": (0, 1), "mha": (heads, 1), "mqa": (1, 1), "cla2": (0, 2), "cla3": (0, 3),
                "custom": (self.cfg.arch_kv_heads, max(1, self.cfg.arch_cla_factor))}[a]

    # ---------------------------------------------------------------- 1. corpus
    def fetch_wikipedia(self, out: Path, target_bytes: int) -> int:
        lang = "".join(c for c in self.cfg.scratch_language if c.isalpha() or c == "-")[:10] or "en"
        base = f"https://{lang}.wikipedia.org/w/api.php?" + urllib.parse.urlencode({
            "action": "query", "format": "json", "generator": "random", "grnnamespace": 0, "grnlimit": 1,
            "prop": "extracts", "explaintext": 1, "exsectionformat": "plain"})
        lock = threading.Lock()
        state = {"bytes": 0, "shard": 0, "buf": [], "buf_bytes": 0, "errors": 0, "articles": 0}

        def flush():
            if state["buf"]:
                (out / f"wiki_{state['shard']:04d}.txt").write_text("\n\n".join(state["buf"]), encoding="utf-8")
                state["shard"] += 1
                state["buf"], state["buf_bytes"] = [], 0

        def one(_):
            if state["bytes"] >= target_bytes or self.control.stopped:
                return
            try:
                r = self.tm.ctx.web._open(base)
                got = parse_wiki_random(r.read(2_000_000))
            except Exception as e:
                if type(e).__name__ == "Stopped":
                    raise
                with lock:
                    state["errors"] += 1
                return
            if not got:
                return
            with lock:
                state["errors"] = 0
                title, text = got
                state["buf"].append(f"{title}\n{text}")
                n = len(text.encode("utf-8"))
                state["bytes"] += n
                state["buf_bytes"] += n
                state["articles"] += 1
                if state["buf_bytes"] > 2_000_000:
                    flush()
                if state["articles"] % 50 == 0:
                    self.say(f"corpus: {state['articles']} articles, {state['bytes'] / 1e6:.1f} MB")

        with ThreadPoolExecutor(max_workers=8) as ex:
            i = 0
            while state["bytes"] < target_bytes:
                self.control.checkpoint()
                list(ex.map(one, range(i, i + 16)))
                i += 16
                if state["errors"] >= 40:
                    raise TrainingError(f"Wikipedia ({lang}) not reachable ({state['errors']} consecutive failures). Check the internet / web policy, "
                                        f"or put .txt files in a folder and set scratch_corpus_dir.")
        flush()
        return state["bytes"]

    def corpus(self) -> list:
        cdir = self.dir / "corpus"
        files = []
        if self.cfg.scratch_corpus_dir:
            d = Path(self.cfg.scratch_corpus_dir)
            files = [str(p) for p in sorted(d.rglob("*")) if p.suffix.lower() in (".txt", ".md") and p.is_file()]
            if not files:
                raise TrainingError(f"no .txt/.md files in {d}")
            self.say(f"corpus: {len(files)} local files from {d}")
            return files
        if not (cdir / "DONE").exists():
            cdir.mkdir(exist_ok=True)
            self.say(f"corpus: fetching ~{self.cfg.scratch_wiki_mb} MB of Wikipedia ({self.cfg.scratch_language})")
            n = self.fetch_wikipedia(cdir, self.cfg.scratch_wiki_mb * 1_000_000)
            (cdir / "DONE").write_text(str(n))
        return [str(p) for p in sorted(cdir.glob("wiki_*.txt"))]

    # ---------------------------------------------------------------- 4. curriculum rows from the Evaluation Core
    def curriculum_rows(self, n: int) -> list:
        probs = self.ctx.evalcore.make_set("train", n)
        rows = []
        for p in probs:
            rows.append({"prompt": p.prompt, "response": oracle_response(p), "src": "curriculum", "domain": p.domain})
        return rows

    # ---------------------------------------------------------------- pipeline
    def build(self) -> str:
        tm, cfg = self.tm, self.cfg
        hw = intake.detect_hardware()
        size = self.pick_size(hw)
        vocab, seq, bs, lr = SIZE_PLAN[size]
        cuda = bool(hw.get("cuda") and hw["gpus"])
        dtype, device = ("bfloat16" if cuda and hw["gpus"][0].get("bf16") else "float16" if cuda else "float32"), ("cuda" if cuda else "cpu")
        kvh, claf = self.arch_params(size)
        self.say(f"building a '{size}' model from scratch on {device} (language: {cfg.scratch_language}, architecture: {cfg.scratch_arch}"
                 f"{f', kv_heads={kvh}' if kvh else ''}{f', CLA factor {claf}' if claf > 1 else ''})")
        files = self.corpus()
        total = sum(os.path.getsize(f) for f in files)
        self.say(f"corpus ready: {total / 1e6:.1f} MB")
        tok_dir = self.dir / "tokenizer"
        if not (tok_dir / "tokenizer.json").exists():
            self.say("training tokenizer")
            tm.run_worker("train_tokenizer", {"corpus_files": files, "vocab_size": max(300, min(vocab, total // 40)), "out_dir": str(tok_dir)}, "tokenizer")
        pre_dir = self.dir / "pretrained"
        if not (pre_dir / "model.safetensors").exists():
            self.say(f"pretraining ({cfg.scratch_steps} steps) - the model learns language only")
            tm.run_worker("pretrain", {"tokenizer_dir": str(tok_dir), "corpus_files": files, "size": size, "seq_len": seq, "batch_size": bs,
                                       "learning_rate": lr, "steps": cfg.scratch_steps, "dtype": dtype, "device": device,
                                       "out_dir": str(pre_dir), "seed": 0, "kv_heads": kvh, "cla_factor": claf}, "pretrain")
        v0 = self.dir / "v0"
        if not (v0 / "model.safetensors").exists():
            self.say("curriculum: first lesson from verified solvers (train problems only)")
            rows = self.curriculum_rows(max(400, cfg.scratch_curriculum_steps * 4))
            ds = self.dir / "curriculum.jsonl"
            ds.write_text("\n".join(json.dumps(r) for r in rows) + "\n")
            epochs = max(0.5, cfg.scratch_curriculum_steps * cfg.micro_batch * cfg.grad_accum / len(rows))
            tm.run_worker("train", {"model_path": str(pre_dir), "dataset_path": str(ds), "out_dir": str(v0), "method": "full",
                                    "dtype": dtype, "device": device, "grad_checkpointing": False, "epochs": epochs,
                                    "learning_rate": min(1e-3, lr / 3), "lora_r": 8, "lora_alpha": 16, "max_len": cfg.max_seq_len,
                                    "micro_batch": cfg.micro_batch, "grad_accum": cfg.grad_accum, "seed": 1,
                                    "train_layers": [], "freeze_patterns": []}, "curriculum")
        self.say(f"model born: {v0}")
        self.tm.db.set_meta("scratch_model", str(v0))
        self.bus.status("scratch_builder", "done", role="scratch_builder", parent="training_maestro")
        return str(v0)
